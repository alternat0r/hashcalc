# Generates the lookup tables used by the PE and similarity hashes:
#
#   src/core/OrdinalNames.inc  Imphash: names of functions imported by ordinal
#                              from ws2_32/wsock32/oleaut32, from pefile's
#                              ordlookup module (MIT license).
#   src/core/TlshTables.inc    TLSH: Pearson table and length table, from the
#                              Trend Micro TLSH reference code (Apache 2.0 / BSD).
#
# Usage: python tools/gen_tables.py <tlsh_impl.cpp> <tlsh_util.cpp>
#        (needs "pip install pefile"; the .cpp files are from
#         https://github.com/trendmicro/tlsh/tree/master/src)
import os
import re
import sys

import ordlookup

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "core")


def c_string(name):
    text = name.decode("ascii") if isinstance(name, bytes) else name
    assert re.fullmatch(r"[A-Za-z0-9_@?$.]+", text), text
    return '"' + text + '"'


def write_ordinals():
    lines = [
        "// Generated by tools/gen_tables.py - do not edit.",
        "// Names of functions that programs import by ordinal from these DLLs, as",
        "// used by Imphash. Data from pefile's ordlookup module (MIT license,",
        "// https://github.com/erocarrera/pefile).",
        "// { dll, ordinal, name }, sorted by dll and ordinal",
    ]
    count = 0
    for dll in sorted(ordlookup.ords):
        for ordinal in sorted(ordlookup.ords[dll]):
            lines.append("{ %s, %d, %s }," % (c_string(dll), ordinal, c_string(ordlookup.ords[dll][ordinal])))
            count += 1
    path = os.path.join(ROOT, "OrdinalNames.inc")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path, count, "names")


def c_array(source, name):
    match = re.search(re.escape(name) + r"\s*\[\d*\]\s*=\s*\{(.*?)\};", source, re.S)
    values = [int(v) for v in re.findall(r"\d+", match.group(1))]
    return values


def write_tlsh(impl_path, util_path):
    impl = open(impl_path, encoding="utf-8").read()
    util = open(util_path, encoding="utf-8").read()
    pearson = c_array(impl, "static unsigned char v_table")
    topval = c_array(util, "unsigned int topval")
    assert len(pearson) == 256 and sorted(pearson) == list(range(256)), "Pearson table must be a permutation"
    assert len(topval) == 170 and topval == sorted(topval), "length table must be ascending"

    def rows(values, per_line):
        return ["    " + ", ".join(str(v) for v in values[i:i + per_line]) + ","
                for i in range(0, len(values), per_line)]

    lines = [
        "// Generated by tools/gen_tables.py - do not edit.",
        "// Tables from the TLSH reference implementation by Trend Micro",
        "// (https://github.com/trendmicro/tlsh, Apache License 2.0 or BSD).",
        "// Copyright 2010-2014 Trend Micro.",
        "",
        "// Pearson's sample random table",
        "const unsigned char kTlshPearson[256] = {",
        *rows(pearson, 16),
        "};",
        "",
        "// Upper bounds of the length buckets (the \"L value\" in the digest)",
        "const unsigned int kTlshTopValue[170] = {",
        *rows(topval, 8),
        "};",
    ]
    path = os.path.join(ROOT, "TlshTables.inc")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    write_ordinals()
    write_tlsh(sys.argv[1], sys.argv[2])
